# -*- coding: utf-8 -*-
"""Последний круг: цена закрытия по дожившей группе, ценность группы, месяцы по кварталу подключения, месяцы с копейками, пилот второго хода при одной частоте случаев."""
import os, io, math, contextlib, importlib.util
D = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location("m6", os.path.join(D, "model6.py"))
m6 = importlib.util.module_from_spec(spec)
with contextlib.redirect_stdout(io.StringIO()):
    spec.loader.exec_module(m6)
m3 = m6.m3; R = m6.R; RATE = 500
def f(x, d=0):
    return f"{round(x, d):,.{d}f}".replace(",", " ").replace(".", ",")
b = m6.OUT["основной"]; r = m3.res["основной"]; w = m3.res["слабый"]; bw = m6.OUT["слабый"]
# 1. цена закрытия по группе, дожившей до конца года
cps = r["cost"] / r["sur"]; rest = 12000 - b["end"]
print(f"Р: Цена группы, дожившей до конца года: расходы {f(R(r['cost']))} рублей делим на {f(r['sur'])} групп, это {f(cps)} рублей; остаток {f(rest)} групп стоит {f(R(rest * cps))} рублей, а при цене подключения 857 рублей {f(R(rest * r['cost'] / r['incr']))} рублей.")
# 2. ценность группы за 36 месяцев
nn = r["nn"]; v_new = nn * RATE * m3.months(36, .70)
v_ret = 3 * RATE * sum(.98 ** t for t in range(36))
print(f"Р: Условная ценность подключённой группы за 36 месяцев: {f(nn, 1)} нового номера, 70 % групп остаётся после бонуса, номер уходит 2 % в месяц, это {f(v_new)} рублей; цена привлечения {f(cps)} рублей за группу, дожившую до конца года, и 857 рублей за подключение; сохранённая от ухода группа из 3 номеров приносит {f(v_ret)} рублей.")
# 3. месяцы по кварталу подключения
q = [[0.0, 0.0] for _ in range(4)]
def add(wj, inc, rb):
    k = min(3, (wj - 1) // 13)
    q[k][0] += inc; q[k][1] += inc * nn * m3.months((52 - wj) / 4.333, rb)
p_ = r["p"]
add(10, 1500 * p_["dA"] / 100, 1.0); add(10, 1500 * p_["dB"] / 100, p_["rb"])
for wk in range(11, 51):
    n = p_["aud"] * (.5 if wk <= 26 else .85)
    add(wk + 2, n * p_["dB"] / 100, p_["rb"])
g = [R(x[0]) for x in q]; mo = [R(x[1]) for x in q]
print(f"Р: Первый ход по кварталу подключения, групп и оплаченных месяцев: первый квартал {f(g[0])} и {f(mo[0])}, второй {f(g[1])} и {f(mo[1])}, третий {f(g[2])} и {f(mo[2])}, четвёртый {f(g[3])} и {f(mo[3])}; всего {f(sum(x[0] for x in q))} групп и {f(sum(mo))} месяцев.")
# 4. месяцы с двумя знаками
for lab, rr, bb in (("основной сценарий", r, b), ("слабый сценарий", w, bw)):
    p1, p2 = R(rr["p1"]), R(rr["p2"])
    c1, c2, c3 = R(rr["cost"]), R(rr["d2"]), R(bb["cost"])
    m1 = (p1 + c1) / RATE; m2 = (p2 + c2) / RATE; m3_ = (bb["p3"] + c3) / RATE
    print(f"Р: Оплаченных месяцев за год, {lab}: первый ход {f(m1, 2)}, второй {f(m2, 2)}, третий {f(m3_, 2)}, всего {f(m1 + m2 + m3_, 2)}; умножить на 500 рублей и вычесть расходы {f(c1)}, {f(c2)} и {f(c3)} рублей, получается {f(p1)}, {f(p2)} и {f(bb['p3'])} рублей.")
# 5. пилот второго хода при одной частоте случаев: 35 % групп за 6 месяцев
h = 1 - (1 - .35) ** (1 / 26)
pool, cum = 1040.0, 0.0
leave = 2100 / 6500 / 52
for wk in range(19, 27):
    ev = h * pool; cum += ev; pool = (pool - ev) * (1 - leave)
n = cum / 2
se = math.sqrt(.10 * .90 / n + .30 * .70 / n)
print(f"Р: Частота случаев одна: 35 % групп за 6 месяцев, это {f(h * 100, 1)} % групп в неделю; пилот на 1 040 группах за 8 недель с 19 по 26 даёт {f(cum)} первых случаев, по {f(n)} в группе проверки; при 10 % против 30 % разброс плюс-минус {f(1.645 * se * 100, 1)} пункта, осторожная оценка разницы {f(20 - 1.645 * se * 100, 1)} при пороге 5; достаточно {f(math.ceil((1.644854 + .841621) ** 2 * (.1 * .9 + .3 * .7) / .2 ** 2))} групп в каждой группе проверки.")
