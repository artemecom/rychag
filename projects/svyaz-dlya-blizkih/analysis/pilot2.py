"""Пилот второго хода на трети подходящих групп: сколько первых случаев к неделе 26 и какая точность ближнего показателя."""
import math
def f(x, d=0):
    return f"{x:,.{d}f}".replace(",", " ").replace(".", ",")
pool, cum = 1040.0, 0.0
h = 1 - (1 - .15) ** .25
leave = 2100 / 6500 / 52
for w in range(19, 26):
    ev = h * pool; cum += ev; pool = (pool - ev) * (1 - leave)
n = cum / 2
se = math.sqrt(.10 * .90 / n + .30 * .70 / n)
print(f"Р: Пилот второго хода: к неделе 26 накоплено {f(cum)} первых случаев, по {f(n)} в варианте; при 10 % против 30 % ширина 90 % интервала плюс-минус {f(1.645 * se * 100, 1)} пункта, нижняя граница разницы {f(20 - 1.645 * se * 100, 1)} при пороге 5.")
n1 = 1.644854 + .841621
need = n1 ** 2 * (.1 * .9 + .3 * .7) / .2 ** 2
print(f"Р: Для разницы 10 % и 30 % достаточно {f(math.ceil(need))} групп в варианте, в пилоте их {f(n)}.")
