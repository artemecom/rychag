# -*- coding: utf-8 -*-
"""Правки по замечаниям проверяющего 5: доля номеров, перестающих платить при распаде группы; просьба с показами недель 11-13; ставка на кону с уходами; цены закрытия остатков."""
import os, io, contextlib, importlib.util
D = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location("m6", os.path.join(D, "model6.py"))
m6 = importlib.util.module_from_spec(spec)
with contextlib.redirect_stdout(io.StringIO()):
    spec.loader.exec_module(m6)
m3 = m6.m3; R = m6.R; RATE = 500
def f(x, d=0):
    return f"{round(x, d):,.{d}f}".replace(",", " ").replace(".", ",")
b = m6.OUT["основной"]; r = m3.res["основной"]
p1, p2 = R(r["p1"]), R(r["p2"])
cost3 = R(b["cost"])
res = {}
for lab, s in (("все номера группы", 1.0), ("половина номеров", .5), ("ни один номер", 0.0)):
    p3 = R(b["mon"] * RATE * s) - cost3
    tot = p1 + p2 + p3
    y2 = R((m6.mo_c + m6.mo_n + s * (m6.mo_r_carry + m6.mo_r_new)) * RATE) - m6.y2_cost
    short = 4350000 - (tot + y2)
    res[lab] = (p3, tot, y2, short)
    print(f"Р: Третий ход, при распаде группы перестают платить {lab}: итог третьего хода за год {f(p3)} рублей, итог года трёх ходов {f(tot)} рублей, прибыль года {f(279 + tot / 1e6, 2)} миллиона рублей; прибыль второго года {f(y2)} рублей; за два года не хватает {f(short)} рублей, с разработкой 450 000 рублей не хватает {f(short + 450000)} рублей.")
# ставка на кону с уходами
pool = r["pool"]; g = pool * .05; nn = r["nn"]
mm = m3.months(12, .70)
inc = g * nn * mm * RATE
cost = pool * (20 + .075 * 300)
print(f"Р: Ставка на кону с уходами и бонусом: {f(g)} групп, {f(g * nn)} новых платящих номеров, за первые 12 месяцев каждый платит {f(mm, 1)} месяца, доход до расходов {f(inc / 1e6, 1)} миллиона рублей при расходах на показы и бонусы {f(cost / 1e6, 1)} миллиона рублей.")
w = m3.res["слабый"]; gw = w["pool"] * .02; nw = gw * w["nn"]; mw = m3.months(12, .40)
print(f"Р: Ставка на кону, слабый сценарий: {f(gw)} групп, {f(nw)} новых платящих номеров, доход до расходов {f(nw * mw * RATE / 1e6, 2)} миллиона рублей при расходах {f(w['pool'] * (40 + .035 * 600) / 1e6, 2)} миллиона рублей.")
# просьба с показами недель 11-13 в первой сумме
t1, t2, t3 = 846281, 1193016, 1605023
show = 49088
print(f"Р: Просьба по частям при 300 000 рублей за человеко-месяц: сейчас {f(t1 + show)} рубль, на неделе 13 ещё {f(t2 - show)} рублей, на неделе 26 ещё {f(t3)} рубля, всего {f(t1 + t2 + t3)} рубля; показы недель 11-13 {f(show)} рубля идут до решения недели 13.")
print(f"Р: Сейчас нужно при 200 000 рублей {f(2.5 * 200000 + 145369)}, при 300 000 рублей {f(t1 + show)}, при 450 000 рублей {f(2.5 * 450000 + 145369)}; наибольшая потеря на неделе 13 в слабом сценарии при 450 000 рублей {f(2.5 * 450000 + 191644)} рубля; к неделе 26 в основном сценарии {f(t1 + t2)} рубля.")
# группы в бонусе и первичный уход
inbonus = lost = 0.0
for wk in range(11, 51):
    n = r["p"]["aud"] * (.5 if wk <= 26 else .85)
    ic = n * r["p"]["dB"] / 100
    rem = (52 - (wk + 2)) / 4.333
    if rem <= 3:
        s_ = ic * m3.surv(rem, r["p"]["rb"]); inbonus += s_; lost += s_ * (1 - r["p"]["rb"])
print(f"Р: Из {f(b['end'])} подключённых групп на конец года {f(inbonus)} групп ещё в периоде бонуса, около {f(lost)} из них уйдут в начале второго года.")
# цена подключения и доля от 100 тысяч
print(f"Р: Первый ход: показано {f(r['exposed'])} домохозяйств, дополнительных групп {f(r['incr'])}, к концу года остаётся {f(r['sur'])}; расходы {f(R(r['cost']))} рублей, это {f(r['cost'] / r['incr'])} рублей за дополнительное подключение; {f(b['end'])} групп на конец года это {f(b['end'] / 1000, 1)} % от 100 тысяч.")
# цены закрытия остатков
cpi = r["cost"] / r["incr"]
rest_c = 12000 - b["end"]; rest_a = 8000 - b["actt"]
print(f"Р: Цена закрытия остатка по подключённым группам {f(rest_c)}: при {f(cpi)} рублей за подключение {f(rest_c * cpi)} рублей, при 2 000 рублей {f(rest_c * 2000)} рублей.")
print(f"Р: Цена закрытия остатка по активным группам {f(rest_a)}: нужно {f(rest_a / .48)} новых групп, при {f(cpi)} рублей {f(rest_a / .48 * cpi)} рублей.")
print(f"Р: Цена закрытия остатка по активации 12 пунктов: четыре меры по 600 000 рублей {f(4 * 600000)} рублей; по владельцам 1 000 подключений по 1 800 рублей {f(1000 * 1800)} рублей.")
# граница в оплаченных месяцах
mon1, mon2, mon3 = R(r["mon"]), R(r["m2"]), R(b["mon"])
need = (6000000 + R(r["cost"]) + R(r["d2"]) + cost3) / RATE
print(f"Р: Граница решения по прибыли 285: разрыв 6 000 000 рублей делим на 500 рублей это 12 000 оплаченных месяцев, с расходами трёх ходов {f(R(r['cost']) + R(r['d2']) + cost3)} рублей нужно {f(need)} месяцев; три хода дают {f(mon1 + mon2 + mon3)} (первый {f(mon1)}, второй {f(mon2)}, третий {f(mon3)}).")
print(f"Р: По 35 % групп со случаем за 6 месяцев в пилоте за 8 недель вышло бы {f(1040 * .35 / 26 * 8)} первых случаев, в расчёте пилота 253: расхождение не снято.")
