# -*- coding: utf-8 -*-
"""Параметры окупаемости kv7: ряд по кварталам из kv6, вложения людей по таблице просьбы: дизайнер 1 и аналитик 1,5 человеко-месяца в первом квартале (750 000 рублей),
дизайнер 1, аналитик 1,5 и тестирование 0,5 во втором (900 000 рублей: 3 человеко-месяца по 300 000), аналитик 1,5 в квартал дальше (450 000 рублей); в слабом сценарии люди только два квартала.
Прежний файл kv6 считал второй квартал в 3,5 человеко-месяца (1 050 000 рублей) и заменён."""
import json, os
D = os.path.dirname(os.path.abspath(__file__))
for src, dst, osn in (("kv6_osnovnoi.json", "kv7_osnovnoi.json", True), ("kv6_slabyi.json", "kv7_slabyi.json", False)):
    d = json.load(open(os.path.join(D, src), encoding="utf-8"))
    d["вложения_по_кварталам"] = [750000, 900000, 450000, 450000, 450000, 450000, 450000, 450000] if osn else [750000, 900000, 0, 0, 0, 0, 0, 0]
    json.dump(d, open(os.path.join(D, dst), "w", encoding="utf-8"), ensure_ascii=False, indent=1)
