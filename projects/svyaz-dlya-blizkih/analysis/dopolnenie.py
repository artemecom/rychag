"""Граница решения с малым запуском каналов и цена разрыва по активации."""
def f(x, d=0):
    return f"{x:,.{d}f}".replace(",", " ").replace(".", ",")
need1 = (6000000 + 150000) / 500
need2 = (6000000 + 150000 + 100000) / 500
print(f"Р: Граница решения: разрыв 6 000 000 рублей и прямые расходы 150 000 рублей дают {f(need1)} месяцев, малый запуск каналов 100 000 рублей добавляет {f(need2 - need1)}, всего {f(need2)} дополнительных оплаченных месяцев.")
gap = 60 - 45
price = 600000
for eff, lab in ((3, "основной"), (5, "сильный"), (1, "слабый")):
    k = gap / eff
    print(f"Р: Цена разрыва по активации, {lab} ход: разрыв {gap} процентных пунктов, одна мера даёт {eff} пункта и стоит {f(price)} рублей, нужно мер {f(k)}, это {f(k * price / 1e6, 1)} миллиона рублей.")
