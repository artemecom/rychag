print(f"Р: Вклад в цели, прибыль: разрыв 6 000 000 рублей; первый ход даёт {f(r['p1'])}, второй {f(r['p2'])}; остаток {f(6000000 - r['p1'] - r['p2'])} рублей.")
# следующие годы по мощности каналов
fresh = r["pool"] - (r["exposed"] - 1500 * 0)  # неоказанные: все, кого не показывали
fresh = max(0.0, r["pool"] - r["exposed"])
a_aud = 770 * 52
