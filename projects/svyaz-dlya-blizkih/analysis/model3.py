print(f"Р: Мощность приложения: 770 показов в неделю это {f(a_aud)} в год; из {f(fresh)} ещё не показанных домохозяйств при приросте 5 пунктов второй год даёт {f(y2_app)} групп, продажи и поддержка 460 групп; расходы второго года {f(y2_cost)} рублей.")
print(f"Р: Подключённых групп к концу первого года {f(round(end_y1))}, к концу второго {f(round(end_y2))}, к концу третьего {f(round(end_y3))}; цель 12 000 в третьем году достигается только если {f(round(end_y3))} не меньше 12 000, повторный показ тем, кто не принял, даёт 681 группу в год при приросте 1,7 пункта.")
print(f"Р: Прибыль второго года от нового хода: {f(mo_c + mo_n)} оплаченных месяцев, итог {f(p_y2)} рублей после расходов {f(y2_cost + 150000)} рублей; цель по прибыли 285 во втором году по этому расчёту {'достигается' if p_y2 >= 6000000 else 'не достигается'}.")
