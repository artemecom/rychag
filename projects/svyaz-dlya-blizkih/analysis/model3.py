"""Модель версии 4. Первый ход: подключение новых семейных групп (предложение с бонусом, проверка с группой без предложения).
Второй ход: предупреждение организатору, пилот на трети подходящих групп. Строки «Р:» идут в реестр.
Новый платный номер: номер ЗАПРОШЕННОГО участника (не организатора), который до приглашения не был абонентом оператора
и заплатил за связь не позднее 12 недель после подключения группы. Организатор и близкие, уже платящие оператору, не считаются.
Новых номеров на подключённую группу = запрошенных участников (кроме организатора) х доля новых."""
import math

def f(x, d=0):
    return f"{x:,.{d}f}".replace(",", " ").replace(".", ",")

START, NOCHANGE, GOAL, EXITS, RATE = 6500, 8000, 12000, 2100, 500
Q = EXITS / START  # годовой уход группы
PM = 300000
SC = {
 "основной": dict(c=.60, aud=770, p0=2.5, dA=1.7, dB=5.0, expc=20, bonus=300, P=2, s=.25, rb=.70, go=True,
                  compat=.60, consent=.80, event=.15, churn_d=.15, uplift=3, prevent=.03, nums=3, dir2=150000, actnew=.48),
 "слабый":   dict(c=.40, aud=400, p0=1.5, dA=.5, dB=2.0, expc=40, bonus=600, P=1, s=.10, rb=.40, go=False,
                  compat=.40, consent=.60, event=.08, churn_d=.02, uplift=1, prevent=0.0, nums=2, dir2=240000, actnew=.46),
 "сильный":  dict(c=.80, aud=1000, p0=3.5, dA=3.0, dB=8.0, expc=10, bonus=150, P=3, s=.50, rb=.90, go=True,
                  compat=.80, consent=.90, event=.25, churn_d=.40, uplift=5, prevent=.10, nums=4, dir2=80000, actnew=.50),
}

def months(rem, rb):
    """оплаченных месяцев одного нового номера за rem месяцев: 3 месяца бонуса полностью, дальше доля оставшихся групп rb; номер уходит 2 % в месяц"""
    m, t = 0.0, 0
    while t < int(rem):
        m += .98 ** t * (1 if t < 3 else rb); t += 1
    return m + (rem - int(rem)) * .98 ** t * (1 if t < 3 else rb)

def surv(rem, rb):
    return (rb if rem > 3 else 1.0) * (1 - Q) ** (rem / 12)

def z2(p1, p2, z=1.644854 + 0.841621):
    return z * z * (p1 * (1 - p1) + p2 * (1 - p2)) / (p1 - p2) ** 2

print("Р: Новых платных номеров на подключённую группу 0,5: запрошенных участников 2 (без организатора) умножить на долю тех, кто до приглашения не был абонентом и заплатил в течение 12 недель, 25 % (допущения); диапазон от 0,1 до 1,5.")
nb = {}
for sc, p in SC.items():
    nn = p["P"] * p["s"]; nb[sc] = nn
brk1 = None
res = {}
for sc, p in SC.items():
    nn = p["P"] * p["s"]
    pool = 100000 * p["c"] - START
    # проверка недель 5-10: три группы по 1 500
    test_cost = 1500 * p["expc"] * 2 + 1500 * (p["p0"] + p["dB"]) / 100 * p["bonus"]
    incA = 1500 * p["dA"] / 100; incB = 1500 * p["dB"] / 100
    exposed = 3000; incr = incA + incB
    mon = incA * nn * months((52 - 10) / 4.333, 1.0) + incB * nn * months((52 - 10) / 4.333, p["rb"])
    sur = incA * surv((52 - 10) / 4.333, 1.0) + incB * surv((52 - 10) / 4.333, p["rb"])
    cost = test_cost
    cost_to26 = test_cost
    expo_q2 = 0.0
    for w in range(11, 51):
        if w <= 26:
            n = p["aud"] * .5          # половина показов на предложение, половина контроль
        elif p["go"]:
            n = p["aud"] * .85
        else:
            n = 0.0
        if n <= 0: continue
        ic = n * p["dB"] / 100
        c1 = n * p["expc"] + n * (p["p0"] + p["dB"]) / 100 * p["bonus"]
        exposed += n; incr += ic; cost += c1
        if w <= 26: cost_to26 += c1; expo_q2 += c1
        rem = (52 - (w + 2)) / 4.333
        mon += ic * nn * months(rem, p["rb"]); sur += ic * surv(rem, p["rb"])
    p1 = mon * RATE - cost
    # ход 2: пилот на трети подходящих групп
    share = p["compat"] * p["consent"]
    prevented = EXITS * .5 * share * (1 / 3) * .5 * p["prevent"]
    end = NOCHANGE + sur + prevented
    conn7 = START + (end - START) / 2
    treated = conn7 * share * p["nums"] / 3 / 2
    ro, rn = .98, .98 + p["churn_d"] / 100
    m2 = treated * sum(rn ** t - ro ** t for t in range(6))
    d2 = p["dir2"] / 3
    p2 = m2 * RATE - d2
    act = NOCHANGE * (.625 + share * (1 / 3) * .5 * p["uplift"] / 100) + sur * p["actnew"]
    res[sc] = dict(incr=incr, sur=sur, mon=mon, cost=cost, p1=p1, p2=p2, prevented=prevented, end=end, act=act, exposed=exposed,
                   pool=pool, test_cost=test_cost, cost_to26=cost_to26, expo_q2=expo_q2, m2=m2, d2=d2, nn=nn, p=p, treated=treated)
    print(f"Р: {sc} сценарий, первый ход: проверка {f(test_cost)} рублей; показано {f(exposed)} домохозяйств; новых групп {f(incr)}, к концу года остаётся {f(sur)}; оплаченных месяцев новых номеров {f(mon)}; расходы {f(cost)} рублей; итог за год {f(p1)} рублей.")
    print(f"Р: {sc} сценарий, второй ход: пилот на {f(treated * 2)} номерах, предотвращено уходов групп {f(prevented)}, оплаченных месяцев {f(m2)}, прямые расходы {f(d2)} рублей, итог за год {f(p2)} рублей.")
    print(f"Р: {sc} сценарий, итоги года: подключённых групп {f(round(end))}, активных групп {f(round(act))}, прибыль {f(279 + (p1 + p2) / 1e6, 2)} миллиона рублей при цели 285.")

r = res["основной"]; w_ = res["слабый"]; s_ = res["сильный"]
# безубыточность первого хода в плановом году
ratio = r["cost"] / (r["mon"] * RATE)
print(f"Р: Первый ход окупает расходы плана года при 0,5 нового номера на группу в {f(1 / ratio, 2)} раза; безубыточное число новых номеров на группу {f(.5 * ratio, 2)}.")
# сколько нужно для цели 285 в плановом году
need_m = (6000000 + r["cost"] - r["p2"] * 0 + r["d2"]) / RATE
print(f"Р: Для прибыли 285 в плановом году нужно {f(need_m)} дополнительных оплаченных месяцев при расходах {f(r['cost'] + r['d2'])} рублей; основной сценарий даёт {f(r['mon'] + r['m2'])}, сильный {f(s_['mon'] + s_['m2'])}.")
print(f"Р: Прибыль сильного сценария года {f(279 + (s_['p1'] + s_['p2']) / 1e6, 2)} миллиона рублей: цель 285 в плановом году достигается только при всех верхних значениях допущений сразу.")
# проверка: точность
se = math.sqrt(.025 * .975 / 1500 + .075 * .925 / 1500)
print(f"Р: Проверка первого квартала: на 1 500 домохозяйств в группе разница подключений 5 пунктов видна с точностью плюс-минус {f(1.645 * se * 100, 1)} пункта, нижняя граница {f(5 - 1.645 * se * 100, 1)}; для разницы 1,7 пункта нужно {f(math.ceil(z2(.025, .042)))} домохозяйств в группе.")
conn = 1500 * .075
sd = math.sqrt(2 * .25 * .75)
print(f"Р: К неделе 13 в группе с бонусом подключилось {f(conn)} групп; новые платные номера за 12 недель видны только у подключившихся к неделе 1 после начала показа, главное допущение 0,5 на группу к неделе 13 не различить.")
print(f"Р: К неделе 23 (12 недель после последнего показа проверки) на {f(conn)} группах новых номеров на группу видно с точностью плюс-минус {f(1.645 * sd / math.sqrt(conn), 2)}; группа осталась после конца бонуса видна к неделе 27.")
# размер под главное допущение: разница новых номеров на 100 показов
m0 = .025 * .5; m1 = .075 * .5; thr = m0 + (.5 * ratio) * .05
n_need = (1.644854 + .841621) ** 2 * (m0 + m1) / (m1 - thr) ** 2
n_pess = (1.644854 + .841621) ** 2 * (m0 + .025 * .2) / (m1 - (m0 + .025 * .2)) ** 2
print(f"Р: Чтобы отличить 0,5 нового номера на группу от безубыточных {f(.5 * ratio, 2)}, нужно {f(n_need)} домохозяйств в каждой из двух групп; чтобы отличить от 0,2 нужно {f(n_pess)}.")
wk = 6 * 257 / 1  # заглушка
n26 = 1500 + 4 * 385   # показано в обеих группах к неделе 14, это 12 недель наблюдения к неделе 26
print(f"Р: К неделе 26 с 12-недельным наблюдением в каждой из двух групп {f(n26)} домохозяйств (показ до недели 14); этого хватает, чтобы отличить 0,5 от 0,2 нового номера на группу, но не от безубыточных {f(.5 * ratio, 2)}; полностью допущение станет видно к неделе {f(26 + (n_need - n26) / 385 + 12 if n_need > n26 else 26)} при дальнейшем делении показов поровну.")
# просьба
people = {1: 1 + 1.5, 2: 1 + 1.5 + .5, 3: 3.0}
tr1 = people[1] * PM + r["test_cost"]
tr2 = people[2] * PM + r["expo_q2"] + r["d2"] / 2
tr3 = people[3] * PM + (r["cost"] - r["cost_to26"]) + r["d2"] / 2
tot = tr1 + tr2 + tr3
print(f"Р: Просьба по частям при 300 000 рублей за человеко-месяц: сейчас {f(tr1)} рублей (люди {f(people[1], 1)} человеко-месяца и проверка), на неделе 13 ещё {f(tr2)} рублей, на неделе 26 ещё {f(tr3)} рублей, всего {f(tot)} рублей.")
pm_lo, pm_hi = 200000, 450000
fix = r["cost"] + r["d2"]
print(f"Р: Всего на год в зависимости от цены человеко-месяца (8,5 человеко-месяцев): при 200 000 рублей {f(8.5 * pm_lo + fix)}, при 300 000 рублей {f(8.5 * PM + fix)}, при 450 000 рублей {f(8.5 * pm_hi + fix)} рублей.")
print(f"Р: Сейчас нужно при 200 000 рублей {f(2.5 * pm_lo + r['test_cost'])}, при 300 000 рублей {f(tr1)}, при 450 000 рублей {f(2.5 * pm_hi + r['test_cost'])} рублей.")
loss26 = 5.5 * pm_hi + w_["cost_to26"] + w_["d2"] / 2
print(f"Р: Наибольшая потеря к неделе 26 при остановке: слабый сценарий и 450 000 рублей за человеко-месяц, {f(loss26)} рублей (люди 5,5 человеко-месяца, показы и бонусы {f(w_['cost_to26'])}); основной сценарий и 300 000 рублей {f(people[1] * PM + people[2] * PM + r['cost_to26'] + r['d2'] / 2)}.")
loss13 = 2.5 * pm_hi + w_["test_cost"]
print(f"Р: Наибольшая потеря при остановке на неделе 13: слабый сценарий и 450 000 рублей, {f(loss13)} рублей; основной сценарий и 300 000 рублей {f(tr1)} рублей.")
# уходы групп
print(f"Р: Уходы групп 2 100 в год: снижение на 10 % сохраняет {f(EXITS * .1)} групп, это {f(EXITS * .1 * 3 * 12 * RATE / 1e6, 2)} миллиона рублей в год платежей их 3 номеров; первый ход добавляет {f(r['sur'])} групп; действие на уходы определим по анализу причин в первом квартале.")
# вклад в цели
print(f"Р: Вклад в цели, подключённые группы: разрыв 4 000; первый ход даёт {f(r['sur'])}, второй {f(r['prevented'])}; остаток {f(GOAL - r['end'])}.")
a1 = r["sur"] * r["p"]["actnew"]; a2 = r["act"] - 5000 - a1
