g2 = res["слабый"]["pool"] * .02; n2 = g2 * res["слабый"]["nn"]
print(f"Р: Ставка на кону, слабый сценарий: {f(g2)} групп и {f(n2)} новых платящих номеров, это {f(n2 * RATE * 12 / 1e6, 2)} миллиона рублей в год.")
be2 = .5 * (y2_cost + 150000) / ((mo_c + mo_n) * RATE)
