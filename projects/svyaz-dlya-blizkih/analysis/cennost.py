"""Условная ценность группы за 36 месяцев и траектория на три года. Строки «Р:» идут в реестр."""
def f(x, d=0):
    return f"{x:,.{d}f}".replace(",", " ").replace(".", ",")
RATE, RET = 500, 0.98
k = sum(RET ** t for t in range(36))
for n in (2, 3, 4):
    print(f"Р: Условная ценность группы из {n} платных номеров за 36 месяцев при ежемесячном удержании 98 %: {f(n * RATE * k)} рублей (допущение об удержании, данных нет).")
start3 = 100000 * 0.15
need_year = (start3 - 8008) / 2
print(f"Р: Ориентир на конец третьего года 15 000 групп (15 % от 100 тысяч); от 8 008 нужно прибавлять по {f(need_year)} групп в год, это при цене 1 525 рублей {f(need_year * 1525 / 1e6, 1)} миллиона рублей в год на привлечение.")
print(f"Р: Ориентир по владельцам на конец третьего года: 2 000 из 40 000 это {f(2000 / 40000 * 100, 1)} % (число цели плановго года, перенесённое на третий год).".replace("плановго", "планового"))
