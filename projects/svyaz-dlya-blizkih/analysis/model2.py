"""Модель версии 3: два первых хода. Ход 1: подключение новых семейных групп (предложение в приложении, проверка в первом квартале, затем охват).
Ход 2: предупреждение организатору. Входные числа: допущения и факты брифа (реестр). Строки «Р:» идут в реестр."""
import math

def f(x, d=0):
    return f"{x:,.{d}f}".replace(",", " ").replace(".", ",")

START, NOCHANGE, GOAL, EXITS, RATE = 6500, 8000, 12000, 2100, 500
NEW = NOCHANGE - START + EXITS
ELIG_SHARE = {"основной": .60, "слабый": .40, "сильный": .80}
# ход 1 по сценариям
M1 = {
 "основной": dict(aud=770, p0=2.5, dA=1.7, dB=5.0, expc=20, bonus=300, nu=.30, nums=3),
 "слабый":   dict(aud=400, p0=1.5, dA=0.5, dB=2.0, expc=40, bonus=600, nu=.10, nums=2),
 "сильный":  dict(aud=1000, p0=3.5, dA=3.0, dB=8.0, expc=10, bonus=150, nu=.60, nums=4),
}
# ход 2 по сценариям
M2 = {
 "основной": dict(compat=.60, consent=.80, event=.15, eff=2, churn_d=.15, uplift=3, prevent=.03, nums=3, dir_cost=150000, act_new=.48),
 "слабый":   dict(compat=.40, consent=.60, event=.08, eff=1, churn_d=.02, uplift=1, prevent=0.0, nums=2, dir_cost=240000, act_new=.46),
 "сильный":  dict(compat=.80, consent=.90, event=.25, eff=4, churn_d=.40, uplift=5, prevent=.10, nums=4, dir_cost=80000, act_new=.50),
}

def z2(p1, p2, z=1.644854 + 0.841621):
    return z * z * (p1 * (1 - p1) + p2 * (1 - p2)) / (p1 - p2) ** 2

print(f"Р: Проверка хода 1 в первом квартале: на 1 500 домохозяйств в каждой из трёх групп (без предложения, предложение, предложение с бонусом); при приросте предложения 1,7 процентного пункта к 2,5 % нужно {f(math.ceil(z2(.025, .042)))} домохозяйств в группе.")
se = math.sqrt(.025 * .975 / 1500 + .075 * .925 / 1500)
print(f"Р: Ход 1, основной: при 2,5 % и 7,5 % у предложения с бонусом ширина 90 % интервала разницы плюс-минус {f(1.645 * se * 100, 1)} процентного пункта; нижняя граница при ожидаемой разнице 5 пунктов {f(5 - 1.645 * se * 100, 1)}.")

res = {}
for sc in M1:
    a, b, c = M1[sc], M2[sc], ELIG_SHARE[sc]
    pool = 100000 * c - START
    # --- ход 1: проверка (недели 5-10), охват (недели 14-50)
    test_cost = 1500 * a["expc"] * 2 + a["bonus"] * 1500 * (a["p0"] + a["dB"]) / 100 + a["bonus"] * 1500 * (a["p0"] + a["dA"]) / 100
    inc_test = 1500 * (a["dA"] + a["dB"]) / 100
    months1 = inc_test * a["nu"] * a["nums"] * (52 - 10) / 4.333
    scale = sc != "слабый"
    inc = cost = expo = 0.0
    if scale:
        for w in range(14, 51):
            n = min(a["aud"], pool - 3000 - expo)
            if n <= 0: break
            ic = n * a["dB"] / 100
            expo += n; inc += ic
            cost += n * a["expc"] + n * (a["p0"] + a["dB"]) / 100 * a["bonus"]
            months1 += ic * a["nu"] * a["nums"] * (52 - (w + 2)) / 4.333
    inc_total = inc + inc_test
    pool_left = pool - 3000 - expo
    # --- ход 2
    share = b["compat"] * b["consent"]
    prevented = EXITS * .5 * share * .5 * b["prevent"]
    end = NOCHANGE + inc_total + prevented
    conn7 = START + (end - START) / 2
    treated = conn7 * share * b["nums"] / 2
    ro, rn = .98, .98 + b["churn_d"] / 100
    months2 = treated * sum(rn ** t - ro ** t for t in range(6))
    act = NOCHANGE * (.625 + share * .5 * b["uplift"] / 100) + inc_total * b["act_new"]
    p1 = months1 * RATE - cost - test_cost
    p2 = months2 * RATE - b["dir_cost"]
    res[sc] = dict(inc_total=inc_total, prevented=prevented, end=end, act=act, p1=p1, p2=p2, cost=cost, test_cost=test_cost,
                   expo=expo, pool_left=pool_left, months1=months1, months2=months2, a=a, b=b, c=c, inc=inc, inc_test=inc_test)
    print(f"Р: {sc} ход, ход 1: проверка стоит {f(test_cost)} рублей и даёт {f(inc_test)} групп; охват с недели 14 {'идёт' if scale else 'не запускается (стоп по итогам первого квартала)'}: показов {f(expo)}, новых групп {f(inc)}, расходы {f(cost)} рублей; дополнительных оплаченных месяцев {f(months1)}; итог хода 1 за год {f(p1)} рублей.")
    print(f"Р: {sc} ход, ход 2: предотвращено уходов {f(prevented)}; удержание на {f(treated)} номерах даёт {f(months2)} дополнительных оплаченных месяцев; прямые расходы {f(b['dir_cost'])} рублей; итог хода 2 за год {f(p2)} рублей.")
    print(f"Р: {sc} ход, итоги года: подключённых групп {f(round(end))}, активных групп {f(round(act))}, активация {f(45 + b['uplift'] if False else 45 + {'основной': 3, 'слабый': 1, 'сильный': 5}[sc])} %, валовая прибыль {f(279 + (p1 + p2) / 1e6, 2)} миллиона рублей при цели 285.")

# --- вклад в цели (основной ход)
r = res["основной"]
print(f"Р: Вклад в цели, подключённые группы: разрыв {f(GOAL - NOCHANGE)}; ход 1 даёт {f(r['inc_total'])}, ход 2 даёт {f(r['prevented'])}; сумма {f(r['inc_total'] + r['prevented'])}; остаток {f(GOAL - r['end'])}.")
a_new = r["inc_total"] * r["b"]["act_new"]
a_m2 = r["act"] - 5000 - a_new
print(f"Р: Вклад в цели, активные группы: разрыв 3 000; ход 1 даёт {f(a_new)}, ход 2 даёт {f(a_m2)}; сумма {f(a_new + a_m2)}; остаток {f(8000 - r['act'])}.")
print(f"Р: Вклад в цели, прибыль: разрыв 6 000 000 рублей; ход 1 даёт {f(r['p1'])}, ход 2 даёт {f(r['p2'])}; сумма {f(r['p1'] + r['p2'])}; остаток {f(6000000 - r['p1'] - r['p2'])} рублей.")
print("Р: Вклад в цели, активация: разрыв 15 процентных пунктов; приглашение участнику с одним касанием даёт 3 пункта; остаток 12 пунктов.")
print("Р: Вклад в цели, владельцы нескольких номеров: разрыв 1 000; действий в плановом году нет, вклад 0, остаток 1 000.")

# --- цены остатков
cpi = (20 + 300 * .075) / .05
rest = GOAL - r["end"]
inc_next = r["pool_left"] * .05
price_next = inc_next * cpi
left = max(0, rest - inc_next)
print(f"Р: Остаток по подключённым группам {f(round(rest))}: оставшаяся база даёт ещё {f(inc_next)} групп по {f(cpi)} рублей, это {f(price_next / 1e6, 1)} миллиона рублей; последние {f(left)} групп через продажи и поддержку по 1 833 рубля это {f(left * 1833 / 1e6, 1)} миллиона рублей.")
act_rest = 8000 - r["act"]
print(f"Р: Остаток по активным группам {f(round(act_rest))}: закрыть можно только новыми группами, {f(act_rest / .48)} групп по 1 833 рубля это {f(act_rest / .48 * 1833 / 1e6, 1)} миллиона рублей.")
print(f"Р: Остаток по активации 12 пунктов: ещё четыре меры по 600 000 рублей это {f(4 * 600000 / 1e6, 1)} миллиона рублей при эффекте одной меры 3 пункта.")
print(f"Р: Остаток по владельцам 1 000: по 1 800 рублей это {f(1000 * 1800 / 1e6, 1)} миллиона рублей.")

# --- следующий год и ставка на кону
for sc in M1:
    x = res[sc]; a = x["a"]; b = x["b"]
    scale = sc != "слабый"
    carry = x["inc_total"] * a["nu"] * a["nums"] * 12
    y2_expo = min(x["pool_left"], a["aud"] * 52) if scale else 0
    y2_inc = y2_expo * a["dB"] / 100
    y2_months = y2_inc * a["nu"] * a["nums"] * 6
    y2_cost = y2_expo * (a["expc"] + (a["p0"] + a["dB"]) / 100 * a["bonus"])
    share = b["compat"] * b["consent"]
    N = NOCHANGE * share * b["nums"]
    ro, rn = .98, .98 + b["churn_d"] / 100
    m2 = N * sum(rn ** t - ro ** t for t in range(12))
    p2y = (carry + y2_months + m2) * RATE - y2_cost - b["dir_cost"]
    print(f"Р: {sc} ход, следующий год: группы первого года дают {f(carry)} оплаченных месяцев новых номеров, новые показы дают {f(y2_months)}, удержание хода 2 {f(m2)}; расходы {f(y2_cost + b['dir_cost'])} рублей; итог года {f(p2y)} рублей.")
    res[sc]["p_y2"] = p2y

# --- ставка на кону при успехе на всей доступной базе
for sc in M1:
    a = M1[sc]; c = ELIG_SHARE[sc]
    base_pool = 100000 * c - START
    g = base_pool * a["dB"] / 100
    nums = g * a["nums"]
    newn = nums * a["nu"]
    print(f"Р: Ставка на кону, {sc} ход: на всей базе из {f(base_pool)} домохозяйств предложение с бонусом даёт {f(g)} групп, {f(nums)} номеров, из них новых платящих {f(newn)}; это {f(newn * RATE * 12 / 1e6, 1)} миллиона рублей валовой прибыли в год при расходах на охват {f(base_pool * (a['expc'] + (a['p0'] + a['dB']) / 100 * a['bonus']) / 1e6, 1)} миллиона рублей.")

# --- окупаемость по кварталам, тысячи рублей, основной ход
people = 9 * 300000
print(f"Р: Люди на год: дизайнер 2, аналитик 6, тестирование 1, всего 9 человеко-месяцев по 300 000 рублей это {f(people)} рублей; разработчики 3 человеко-месяца уже выделены предварительно.")
ask_now = 2.5 * 300000 + r["test_cost"]
q2 = 3.5 * 300000 + 13 * 770 * (20 + .075 * 300)
h2 = 3.0 * 300000 + (r["cost"] - 13 * 770 * (20 + .075 * 300)) + 150000
print(f"Р: Просьба по срокам: сейчас {f(ask_now)} рублей (люди 2,5 человеко-месяца и проверка хода 1), на второй квартал {f(q2)} рублей, на вторую половину года {f(h2)} рублей, всего {f(ask_now + q2 + h2)} рублей.")
# --- траектория и ориентир
y2_end = r["end"] + min(r["pool_left"], 770 * 52) * .05
print(f"Р: Траектория подключённых групп, основной ход: конец первого года {f(round(r['end']))}, конец второго {f(round(y2_end))} при том же предложении; ориентир на конец третьего года 13 000 групп, 13 % от 100 тысяч домохозяйств.")

# --- ближний показатель хода 2 и ширина интервала главного результата (с выбытием групп)
b = M2["основной"]
elig0 = START * b["compat"] * b["consent"]
h = 1 - (1 - b["event"]) ** .25
leave = EXITS / START / 52
join = NEW / 52 * b["compat"] * b["consent"]
rem = cum = 0.0
cumw = {}
for w in range(19, 80):
    if w == 19: rem += elig0
    ev = h * rem
    rem -= ev
    cum += ev
    rem = rem * (1 - leave) + join
    cumw[w] = cum
n_main = math.ceil(z2(.12, .09))
reach = next((w for w in sorted(cumw) if cumw[w] >= 2 * n_main), None)
print(f"Р: Ход 2, основной: подходящих групп с согласием {f(elig0)}; к неделе 26 накоплено {f(cumw[26])} первых случаев, к неделе 51 {f(cumw[51])}; нужные {f(2 * n_main)} для разницы 12 % и 9 % набираются к неделе {reach} с учётом выбытия групп, то есть без запаса до конца года.")
nn = cumw[51] / 2
print(f"Р: Ход 2, основной: к неделе 51 по {f(nn)} групп в варианте; ширина 90 % интервала разницы плюс-минус {f(1.645 * math.sqrt(2 * .12 * .88 / nn) * 100, 1)} процентного пункта, при ожидаемой разнице 2 пункта главный результат за год не различить, решение о расширении опирается на ближний показатель.")
n26 = cumw[25] / 2
se2 = math.sqrt(.10 * .90 / n26 + .30 * .70 / n26)
print(f"Р: Ход 2, основной: к неделе 25 по {f(n26)} групп в варианте; доля выделений в течение 48 часов 10 % против 30 %, ширина 90 % интервала разницы плюс-минус {f(1.645 * se2 * 100, 1)} процентного пункта, нижняя граница {f(20 - 1.645 * se2 * 100, 1)}; порог: разница не менее 10 процентных пунктов при нижней границе не ниже 5.")
print(f"Р: Ход 2: для ближнего показателя при 10 % и 30 % достаточно {f(math.ceil(z2(.10, .30)))} групп в варианте.")
# --- безубыточные значения
r = res["основной"]
nu_y1 = .30 * (r["cost"] + r["test_cost"]) / (r["months1"] * RATE)
print(f"Р: Ход 1 окупает себя в первый год, если доля дополнительных групп с новыми платными номерами не ниже {f(nu_y1 * 100, 1)} %.")
need_y2 = (6000000 + 1085425) / RATE
nu_y2 = .30 * (need_y2 - 1003) / (16470 + 5943)
print(f"Р: Цель по прибыли 285 во втором году достигается при доле дополнительных групп с новыми платными номерами не ниже {f(nu_y2 * 100, 1)} % (основное значение 30 %).")
