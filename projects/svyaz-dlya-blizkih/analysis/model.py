"""Модель плана: поток случаев, подключённые, активные, прибыль, окупаемость, цены разрывов.
Все входные числа заданы допущениями и фактами брифа (см. реестр). Выводит строки, начинающиеся с «Р:»."""
import math

def f(x, d=0):
    s = f"{x:,.{d}f}".replace(",", " ").replace(".", ",")
    return s

S = {
 "основной": dict(compat=.60, consent=.80, event=.15, eff=3, churn_d=.15, uplift=3, prevent=.03, nums=3, dir_cost=60000 + 90000),
 "слабый":   dict(compat=.40, consent=.60, event=.08, eff=1, churn_d=.02, uplift=1, prevent=0.0, nums=2, dir_cost=90000 + 150000),
 "сильный":  dict(compat=.80, consent=.90, event=.25, eff=5, churn_d=.40, uplift=5, prevent=.10, nums=4, dir_cost=30000 + 50000),
}
START, NOCHANGE, GOAL = 6500, 8000, 12000
EXITS = 2100
NEW = NOCHANGE - START + EXITS
TEST_COST = 100000
RATE = 500

def zsum(p1, p2, z=1.644854 + 0.841621):
    return z * z * (p1 * (1 - p1) + p2 * (1 - p2)) / (p1 - p2) ** 2

# --- поток случаев и срок
def flow(sc, target):
    p = S[sc]
    elig0 = START * p["compat"] * p["consent"]
    h = 1 - (1 - p["event"]) ** .25
    join = NEW / 52 * p["compat"] * p["consent"]
    rem, cum, out = 0.0, 0.0, {}
    reached = None
    for w in range(19, 120):
        if w == 19:
            rem += elig0
        fr = 1
        ev = h * rem
        rem -= ev
        cum += ev
        rem += join * fr
        out[w] = cum
        if reached is None and cum >= target:
            reached = w
    return elig0, h, out, reached

n_main = math.ceil(zsum(.12, .09))
n_prox = math.ceil(zsum(.10, .30))
print(f"Р: Число групп для сравнения 12 % и 9 % (односторонняя проверка, риск ошибки 5 %, мощность 80 %): {f(n_main)} в каждой, {f(2 * n_main)} всего.")
print(f"Р: Число групп для ближнего показателя 10 % и 30 % (односторонняя проверка): {f(n_prox)} в каждой, {f(2 * n_prox)} всего.")
for sc in S:
    e0, h, out, reached = flow(sc, 2 * n_main)
    print(f"Р: {sc} ход: подходящих групп с согласием на начало года {f(e0)}; к концу второго квартала (неделя 26) накоплено {f(out[26])} первых случаев, к концу третьего (неделя 39) {f(out[39])}, к концу года (неделя 52) {f(out[52])}.")
    if reached:
        wk = reached + 1
        q = "второго" if wk <= 26 else "третьего" if wk <= 39 else "четвёртого" if wk <= 52 else "следующего года"
        print(f"Р: {sc} ход: нужные {f(2 * n_main)} первых случаев набираются к неделе {reached}, итог с неделей наблюдения на неделе {wk} от начала планового года ({q} квартала).")
    else:
        print(f"Р: {sc} ход: нужные {f(2 * n_main)} первых случаев не набираются за 120 недель.")
    # ближний показатель
    wp = next((w for w in sorted(out) if out[w] >= 2 * n_prox), None)
    print(f"Р: {sc} ход: {f(2 * n_prox)} первых случаев для ближнего показателя набираются к неделе {wp}.")
e0, h, out, reached = flow("основной", 2 * n_main)
n_int = out[51] / 2
lo, hi = 0.001, 0.12
for _ in range(60):
    mid = (lo + hi) / 2
    if zsum(.12, .12 - mid) > n_int: lo = mid
    else: hi = mid
print(f"Р: Основной ход: к неделе 51 накоплено {f(out[51])} первых случаев, по {f(n_int)} в группе; при 12 % различима разница не меньше {f(hi * 100, 1)} процентных пунктов.")

n25 = out[25] / 2
lo, hi = 0.001, 0.12
for _ in range(60):
    mid = (lo + hi) / 2
    if zsum(.12, .12 - mid) > n25: lo = mid
    else: hi = mid
print(f"Р: Основной ход: к неделе 25 накоплено {f(out[25])} первых случаев, по {f(n25)} в группе; при 12 % различима разница не меньше {f(hi * 100, 1)} процентных пунктов, этого мало для 3, поэтому второй квартал решает по ближнему показателю.")

# --- подключённые, активные, удержание, прибыль
res = {}
for sc, p in S.items():
    share = p["compat"] * p["consent"]
    prevented = EXITS * .5 * share * .5 * p["prevent"]
    end = NOCHANGE + prevented
    act_share = .625 + share * .5 * p["uplift"] / 100
    act = end * act_share
    conn7 = START + (end - START) / 2
    treated_nums = conn7 * share * p["nums"] / 2
    ro, rn = .98, .98 + p["churn_d"] / 100
    months = treated_nums * sum(rn ** t - ro ** t for t in range(6))
    profit = months * RATE - p["dir_cost"] - TEST_COST
    res[sc] = dict(end=end, act=act, months=months, profit=profit, share=share, nums=p["nums"], d=p["churn_d"])
    print(f"Р: {sc} ход: предотвращено уходов групп {f(prevented)}; подключённых групп на конец года {f(round(end))}; доля активных {f(act_share * 100, 1)} %, активных групп {f(round(act))}.")
    print(f"Р: {sc} ход: удержание на {f(treated_nums)} номерах с седьмого месяца даёт {f(months)} дополнительных оплаченных месяцев, вклад {f(months * RATE)} рублей; прямые расходы {f(p['dir_cost'])} рублей и малый запуск каналов {f(TEST_COST)} рублей; итог года {f(profit)} рублей к 279 миллионам.")
    print(f"Р: {sc} ход: валовая прибыль года {f(279 + profit / 1e6, 2)} миллиона рублей при цели 285, не хватает {f(285 - 279 - profit / 1e6, 2)} миллиона рублей.")

# --- разложение отставания базового года
g_eff = (7500 - 6500) * 5000 / 7500
s_eff = 6500 * (5000 / 7500 - 4000 / 6500)
print(f"Р: Отставание базового года по активным группам 1 000: из-за меньшего числа подключённых групп {f(g_eff)}, из-за меньшей доли активных {f(s_eff)} (доля {f(4000 / 6500 * 100, 1)} % против {f(5000 / 7500 * 100, 1)} %).")

# --- доли охвата
print(f"Р: Охват на конец года в основном ходе: {f(res['основной']['end'] / 100000 * 100, 1)} % от 100 тысяч домохозяйств; владельцы 1 000 из 40 000 это {f(1000 / 40000 * 100, 1)} %.")

# --- цены разрывов
cpc, cpc_lo, cpc_hi = 1200000 / 787, 1222, 2000
gap_c = GOAL - res["основной"]["end"]
print(f"Р: Цена разрыва по подключённым группам: не хватает {f(round(gap_c))}; при цене дополнительного подключения {f(cpc)} рублей это {f(gap_c * cpc / 1e6, 1)} миллиона рублей (от {f(gap_c * cpc_lo / 1e6, 1)} до {f(gap_c * cpc_hi / 1e6, 1)}); цена растёт с охватом.")
gap_a = 8000 - res["основной"]["act"]
print(f"Р: Разрыв по активным группам {f(round(gap_a))}; при 12 000 подключённых нужна доля активных 66,7 %, у полного охвата предупреждения даёт {f(.6 * .8 * 3, 1)} процентного пункта к 62,5 %.")
cab = 8 * 300000
print(f"Р: Кабинет с объёмом 8 человеко-месяцев по 300 000 рублей стоит {f(cab / 1e6, 1)} миллиона рублей; вместе с ценой подключений цена разрыва по активным группам {f((gap_c * cpc + cab) / 1e6, 1)} миллиона рублей.")
print(f"Р: Цена разрыва по владельцам: 1 000 подключений по 1 800 рублей это {f(1000 * 1800 / 1e6, 1)} миллиона рублей (от {f(1000 * 1200 / 1e6, 1)} до {f(1000 * 2500 / 1e6, 1)}).")
need = (6000000 + 150000) / RATE
N2 = NOCHANGE * .6 * .8 * 3
d_star = need / (N2 * 66) * 100
print(f"Р: Прибыль: нужно {f(need)} дополнительных оплаченных месяцев; при полном годе работы на {f(N2)} номерах это снижение месячного ухода на {f(d_star, 2)} процентного пункта при сильном ходе 0,4.")
for nu in (.10, .30, .60):
    groups = need / (3 * nu * 12)
    print(f"Р: Прибыль через подключения: если {f(nu * 100)} % дополнительных групп приносят новые платные номера, нужно {f(round(groups))} дополнительных групп за полный год, при цене {f(cpc)} рублей это {f(groups * cpc / 1e6, 1)} миллиона рублей.")

# --- второй год и окупаемость (полный год охвата)
for sc in S:
    p = S[sc]
    N = NOCHANGE * p["compat"] * p["consent"] * p["nums"]
    ro, rn = .98, .98 + p["churn_d"] / 100
    m2 = N * sum(rn ** t - ro ** t for t in range(12))
    prof2 = m2 * RATE - p["dir_cost"]
    print(f"Р: {sc} ход, следующий год при охвате всех совместимых групп с января: {f(N)} номеров, {f(m2)} дополнительных оплаченных месяцев, прибыль после прямых расходов {f(prof2)} рублей.")
print(f"Р: Люди: дизайнер 2, аналитик 3, тестирование 1, всего 6 человеко-месяцев по 300 000 рублей это {f(6 * 300000)} рублей; разработчики 3 человеко-месяца это {f(3 * 300000)} рублей.")
