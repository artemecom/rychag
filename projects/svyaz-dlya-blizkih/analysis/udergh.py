"""Безубыточность третьего хода: расходы делим на прибыль от каждого процента снижения уходов."""
def f(x, d=0):
    return f"{x:,.{d}f}".replace(",", " ").replace(".", ",")
cost, profit_at_5 = 21180, 358830 + 21180
per_pct = profit_at_5 / 5
print(f"Р: Удержание окупается при снижении уходов неактивных групп от {f(cost / per_pct, 2)} %: расходы {f(cost)} рублей, сохранённая прибыль {f(per_pct)} рублей на каждый процент снижения.")
