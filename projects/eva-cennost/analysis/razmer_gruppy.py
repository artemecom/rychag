# Прикидка размера группы: n = 16 * p * (1 - p) / d^2. Исходные p и d НЕ из данных, а выбор планирования (внутренних данных о продлении нет).
for p in (0.2, 0.3, 0.5):
    for d in (0.05, 0.10):
        n = 16 * p * (1 - p) / (d * d)
        print("Базовая доля продливших %.0f%%, различие %.0f п.п.: нужно около %d человек на группу" % (p * 100, d * 100, round(n)))
