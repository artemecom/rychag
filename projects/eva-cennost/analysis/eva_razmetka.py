# Ручная разметка 100 отзывов RuStore со словом «Ева» (номера по порядку от новых к старым).
# Разметил агент по прочтению каждого отзыва; вторым человеком не проверено.
import csv
import re
import sys

with open(sys.argv[1], encoding="utf-8", newline="") as f:
    rows = list(csv.DictReader(f))
ev = [r for r in rows if re.search(r"\bев[аыуе]\b|\bевой\b", r["text"], re.I)]

THEMES = {
    "чат поддержки (бот Ева не соединяет с оператором)": [1, 2, 4, 5, 7, 8, 13, 14, 15, 16, 17, 19, 20, 21, 30, 31, 32, 33, 37, 58, 85],
    "хвалят: Ева отвечает мошенникам и блокирует спам": [0, 3, 29, 43, 45, 49, 50, 51, 61, 63, 70, 73, 92, 95],
    "блокирует нужные номера (близкие, контакты, курьер)": [10, 22, 24, 35, 41, 57],
    "секретарь перехватывает звонки, которых человек ждёт": [9, 18, 42, 65, 76, 83, 64],
    "защита не срабатывает, спам идёт дальше": [27, 36, 39, 44],
    "жалобы на платное: списания, навязанная Ева+": [6, 11, 23],
    "недоверие: «сами спамят, чтобы продать Еву»": [40, 82],
    "просьбы: белый список, убрать из спама, имя звонившего и т.п.": [28, 47, 54, 56, 66, 86, 91, 94, 38, 67, 71],
}
used = set()
for name, ids in THEMES.items():
    rs = [ev[i] for i in ids]
    used.update(ids)
    avg = sum(int(r["rating"]) for r in rs) / len(rs)
    low = sum(1 for r in rs if int(r["rating"]) <= 2)
    print("%s: %d отзывов, средняя оценка %.2f, оценок 1-2: %d" % (name, len(rs), avg, low))
rest = [i for i in range(len(ev)) if i not in used]
rs = [ev[i] for i in rest]
print("сбои и неудобства экрана Евы в приложении (вылеты, история звонков, окна, настройки) и прочее: %d отзывов, средняя оценка %.2f" % (len(rs), sum(int(r["rating"]) for r in rs) / len(rs)))
print("Всего размечено: %d из %d отзывов с упоминанием Евы, период данных %s - %s" % (len(ev), len(rows), min(r["date"] for r in rows), max(r["date"] for r in rows)))
print("Отзывов 5 звёзд среди хвалящих: %d из %d" % (sum(1 for i in THEMES["хвалят: Ева отвечает мошенникам и блокирует спам"] if int(ev[i]["rating"]) == 5), len(THEMES["хвалят: Ева отвечает мошенникам и блокирует спам"])))
