# Доли тем среди отзывов 1-2 за весь период (9103 отзыва) с поправкой на точность и полноту словаря.
# Поправка = доля словаря * точность / полнота; точность и полнота объединены по двум выборкам по 150 отзывов (S014, S024).
# (совпало, попало_по_словарю, отметил_судья) на каждой выборке.
SAMPLES = {
    "бот": [(44, 44, 46), (24, 24, 24)],
    "нет живого человека": [(39, 57, 41), (28, 46, 30)],
    "самоподключение и списания": [(20, 42, 22), (15, 30, 16)],
    "сбои приложения": [(17, 26, 30), (30, 43, 45)],
}
DICT_SHARE = {"бот": 21.3, "нет живого человека": 31.4, "самоподключение и списания": 20.5, "сбои приложения": 23.4}
for k, s in SAMPLES.items():
    tp = sum(x[0] for x in s)
    hit = sum(x[1] for x in s)
    jud = sum(x[2] for x in s)
    p, r = tp / hit, tp / jud
    print("%s: по словарю %.1f%%, точность %.0f%%, полнота %.0f%%, с поправкой около %.1f%%" % (k, DICT_SHARE[k], 100 * p, 100 * r, DICT_SHARE[k] * p / r))
