# Инерция рейтинга RuStore: сколько новых оценок со средним m нужно, чтобы поднять общий рейтинг с 3,2 до цели.
# Вход со страницы RuStore (S004): рейтинг 3,2, 29 700 оценок. Сколько оценок приходит в месяц, неизвестно (запрос руководителю).
# Рейтинг округлён до 0,1, поэтому результат ориентировочный (допущение).
total, rating = 29700, 3.2
print("Нужно новых оценок N, чтобы общий рейтинг достиг цели, если новые оценки в среднем m (N = (цель - рейтинг) * всего / (m - цель))")
for target in (3.4, 3.5, 3.8):
    for m in (4.0, 4.2, 4.5):
        n = (target - rating) * total / (m - target)
        print("цель %.1f, новые в среднем %.1f: нужно %d новых оценок (%.0f%% от текущих 29 700)" % (target, m, n, 100 * n / total))
print("Если новые оценки идут в среднем как выгрузка (около 2,0), рейтинг не растёт: 2,0 ниже текущих 3,2")
