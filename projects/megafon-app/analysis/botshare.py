# База для рычага «бот и живой человек» и прикидка срока проверки по отзывам RuStore.
# Метрика: доля ВСЕХ отзывов (любая оценка) месяца, где прямо названы бот, робот, ИИ, Елена или ассистент (словарь как в themes.py).
import csv
import re
import sys
from collections import defaultdict

BOT = r"\bбот\w*|\bробот(?!у)\w*|\bии\b|нейросет|ассистент|виртуальн|елен[аыуе]\b|автоответ|по кругу"
SMEZH = r"списыва|списал|снима|снял|подключа|подключил|подключен|навязыва|платн|подписк|развод|обман|воруют|воры|мошен|без моего|без спроса|без ведома|ева\b"
CRASH = r"не открыва|вылета|белый экран|глюч|тормоз|завис|не грузит|не загружа|ошибк|не работает|баг|лагает|крашит|слетает|не запуска"

with open(sys.argv[1], encoding="utf-8", newline="") as f:
    rows = list(csv.DictReader(f))

by = defaultdict(lambda: [0, 0, 0, 0])
for r in rows:
    m = r["date"][:7]
    t = r["text"].lower()
    by[m][0] += 1
    by[m][1] += bool(re.search(BOT, t))
    by[m][2] += bool(re.search(SMEZH, t))
    by[m][3] += bool(re.search(CRASH, t))

print("месяц | отзывов | бот, % | самоподключение и списания, % | сбои, %")
for m in sorted(by):
    n, b, s, c = by[m]
    print("%s | %d | %.1f | %.1f | %.1f" % (m, n, 100 * b / n, 100 * s / n, 100 * c / n))

last = [m for m in ("2026-09", "2026-10", "2026-11")]
n = sum(by[m][0] for m in last)
b = sum(by[m][1] for m in last)
s = sum(by[m][2] for m in last)
c = sum(by[m][3] for m in last)
print("База 2026-09..11: отзывов %d, бот %.1f%%, самоподключение %.1f%%, сбои %.1f%%" % (n, 100 * b / n, 100 * s / n, 100 * c / n))
weeks = (18 + 30 + 31) / 7.0  # дней в окне 01.09-18.11: 30 + 31 + 18 = 79
weeks = 79 / 7.0
print("Отзывов в неделю в окне 2026-09-01..2026-11-18: %.0f" % (n / weeks))

p = b / n
print("Прикидка числа отзывов на период по 16*p*(1-p)/d^2, p = %.3f:" % p)
for d in (0.03, 0.05, 0.07):
    need = 16 * p * (1 - p) / d ** 2
    print("d = %.0f п.п.: %d отзывов на период, около %.1f недель при текущем потоке" % (100 * d, need, need / (n / weeks)))
