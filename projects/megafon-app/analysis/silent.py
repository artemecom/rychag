# Арифметика: какой должна быть средняя оценка тех, кто оценил без текста, чтобы общий рейтинг RuStore был 3,2.
# Входы со страницы RuStore (S004): рейтинг 3,2, 29 700 оценок, 11 221 отзыв. Средняя по отзывам: допущение, что она
# равна средней по выгрузке (1,59, S002) или лежит в диапазоне 1,5-2,0. Допущение, не факт: проверить нечем.
total, rating, reviews = 29700, 3.2, 11221
silent_n = total - reviews
print("Оценок без текста: %d (%.1f%% всех оценок)" % (silent_n, 100 * silent_n / total))
for rm in (1.5, 1.59, 2.0):
    s = (rating * total - rm * reviews) / silent_n
    print("Если отзывы в среднем %.2f, то оценки без текста в среднем %.2f" % (rm, s))
print("Ограничение: рейтинг 3,2 округлён, диапазон 3,15-3,25 сдвигает результат примерно на 0,1")
