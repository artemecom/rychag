# Вклад тем в изменение доли плохих отзывов (оценка 1-2) между периодами до и после просадки 2025 года
# и проверка на срезе, которого причина «изменение чата или бота» касаться не должна.
# Вход: полная выгрузка отзывов RuStore. Метод: словарь слов (как в themes.py); границы периодов выбраны нами.
import csv
import random
import re
import sys

BOT = r"\bбот\w*|\bробот(?!у)\w*|\bии\b|нейросет|ассистент|виртуальн|елен[аыуе]\b|автоответ|по кругу"
SUPPORT = r"\bбот\w*|\bробот(?!у)\w*|ассистент|виртуальн|помощник|живо[йгм]|елен[аыуе]\b|автоответ|по кругу|не соедин\w+|не переключ\w+|соедин\w+ с оператор|переключ\w+ на оператор|связ\w+ с (оператор|человек|поддержк|живым)|дозвон\w+|достучат\w+|поддержк|оператор"
THEMES = {
    "бот назван прямо": BOT,
    "самоподключение и списания": r"списыва|списал|снима|снял|подключа|подключил|подключен|навязыва|платн|подписк|развод|обман|воруют|воры|мошен|без моего|без спроса|без ведома|ева\b",
    "цены и тарифы": r"цен[аыуе]|тариф|подорож|дорого|дорож|повыш|повыс|рубл|абонентск",
    "связь и интернет": r"\bсвяз[ьи]\b(?! с )|интернет|не ловит|скорост|вышк|медленн|блокиров|покрыти|lte|4g|3g",
    "сбои приложения": r"не открыва|вылета|белый экран|глюч|тормоз|завис|не грузит|не загружа|ошибк|не работает|баг|лагает|крашит|слетает|не запуска",
    "вход и коды": r"вход|войти|авториз|парол|смс|код\b|коды|подтвержден|не прих",
    "интерфейс и понятность": r"шрифт|интерфейс|дизайн|неудобн|неудобно|непонятн|реклам|баннер|навязчив|запутан|сложно",
    "пополнение и оплата": r"пополн|оплат|платёж|платеж|карт[аыуой]|сбп|баланс",
}

with open(sys.argv[1], encoding="utf-8", newline="") as f:
    rows = list(csv.DictReader(f))
for r in rows:
    r["low"] = int(r["rating"]) <= 2
    t = r["text"].lower()
    r["bot"] = bool(re.search(BOT, t))
    r["sup"] = bool(re.search(SUPPORT, t))
    r["th"] = {k: bool(re.search(rx, t)) for k, rx in THEMES.items()}


def pick(a, b):
    return [r for r in rows if a <= r["date"] <= b]


def delta_boot(pb, pa, fn, n=1000, seed=7):
    """Разность долей fn (в п.п.) после минус до, 95% интервал по 1000 перевыборок отзывов."""
    rnd = random.Random(seed)
    out = []
    for _ in range(n):
        sb = [rnd.choice(pb) for _ in pb]
        sa = [rnd.choice(pa) for _ in pa]
        out.append(100 * (fn(sa) - fn(sb)))
    out.sort()
    return out[int(0.025 * n)], out[int(0.975 * n)]


def share(pred, den=None):
    def f(rs):
        d = rs if den is None else [r for r in rs if den(r)]
        return sum(1 for r in d if pred(r)) / len(d) if d else 0.0
    return f


PAIRS = (
    ("Основная пара: до = 2025-03-01..2025-04-30, после = 2025-07-01..2025-08-31", ("2025-03-01", "2025-04-30"), ("2025-07-01", "2025-08-31")),
    ("Проверка границ: до = 2025-01-01..2025-03-31, после = 2025-07-01..2025-09-30", ("2025-01-01", "2025-03-31"), ("2025-07-01", "2025-09-30")),
)

for title, (b1, b2), (a1, a2) in PAIRS:
    pb, pa = pick(b1, b2), pick(a1, a2)
    print("== %s" % title)
    print("Отзывов до: %d, после: %d" % (len(pb), len(pa)))
    allbad = share(lambda r: r["low"])
    d = 100 * (allbad(pa) - allbad(pb))
    lo, hi = delta_boot(pb, pa, allbad)
    print("Доля плохих отзывов (оценка 1-2) среди всех отзывов: до %.1f%%, после %.1f%%, изменение %+.1f п.п. (95%% интервал %+.1f..%+.1f)" % (100 * allbad(pb), 100 * allbad(pa), d, lo, hi))
    print("Разбиение на «бот назван» и «бот не назван» (части не пересекаются, сумма равна общему изменению):")
    for lab, fn in (("плохие со словом про бота", share(lambda r: r["low"] and r["bot"])), ("плохие без слов про бота", share(lambda r: r["low"] and not r["bot"]))):
        dd = 100 * (fn(pa) - fn(pb))
        lo, hi = delta_boot(pb, pa, fn)
        print("  %s: до %.1f%%, после %.1f%% от всех отзывов, вклад %+.1f п.п. (интервал %+.1f..%+.1f), доля от общего изменения %.0f%%" % (lab, 100 * fn(pb), 100 * fn(pa), dd, lo, hi, 100 * dd / d))
    print("Вклад тем (отзывы 1-2 с темой, доля от ВСЕХ отзывов периода; темы пересекаются, сумма не равна общему изменению):")
    for t in THEMES:
        fn = share(lambda r, t=t: r["low"] and r["th"][t])
        dd = 100 * (fn(pa) - fn(pb))
        lo, hi = delta_boot(pb, pa, fn)
        print("  %s: до %.1f%%, после %.1f%%, вклад %+.1f п.п. (интервал %+.1f..%+.1f)" % (t, 100 * fn(pb), 100 * fn(pa), dd, lo, hi))
    fn = share(lambda r: r["low"] and not any(r["th"].values()))
    dd = 100 * (fn(pa) - fn(pb))
    lo, hi = delta_boot(pb, pa, fn)
    print("  без темы словаря: до %.1f%%, после %.1f%%, вклад %+.1f п.п. (интервал %+.1f..%+.1f)" % (100 * fn(pb), 100 * fn(pa), dd, lo, hi))

    print("-- Проверка на срезе, которого причина (изменение чата или бота) не касается --")
    ctrl = {
        "срез А: отзывы без слов про бота и поддержку": lambda r: not r["sup"],
        "срез Б: отзывы про связь и интернет без слов про бота и поддержку": lambda r: r["th"]["связь и интернет"] and not r["sup"],
        "срез В: отзывы про цены и тарифы без слов про бота и поддержку": lambda r: r["th"]["цены и тарифы"] and not r["sup"],
        "срез Г (для сравнения, причина касается): отзывы со словом про бота": lambda r: r["bot"],
    }
    for lab, cond in ctrl.items():
        sb = [r for r in pb if cond(r)]
        sa = [r for r in pa if cond(r)]
        if not sb or not sa:
            print("  %s: пусто" % lab)
            continue
        fn = share(lambda r: r["low"])
        rnd = random.Random(7)
        outs = []
        for _ in range(1000):
            x = [rnd.choice(sb) for _ in sb]
            y = [rnd.choice(sa) for _ in sa]
            outs.append(100 * (fn(y) - fn(x)))
        outs.sort()
        print("  %s: отзывов до %d, после %d; доля плохих до %.1f%%, после %.1f%%, изменение %+.1f п.п. (интервал %+.1f..%+.1f)" % (
            lab, len(sb), len(sa), 100 * fn(sb), 100 * fn(sa), 100 * (fn(sa) - fn(sb)), outs[25], outs[975]))
    print("  Доля отзывов с любыми словами про бота и поддержку: до %.1f%%, после %.1f%%" % (100 * share(lambda r: r["sup"])(pb), 100 * share(lambda r: r["sup"])(pa)))
    print("  Доля отзывов со словами про бота: до %.1f%%, после %.1f%%" % (100 * share(lambda r: r["bot"])(pb), 100 * share(lambda r: r["bot"])(pa)))
