# Темы жалоб в отзывах с оценкой 1-2: словарь слов, один отзыв может попасть в несколько тем.
# Метод простой (поиск слов), точность проверяется ручной выборкой, см. analysis/diagnoz.md.
import csv
import re
import sys
from collections import Counter

THEMES = {
    "бот назван прямо (бот, робот, ИИ, Елена, ассистент)": r"\bбот\w*|\bробот(?!у)\w*|\bии\b|нейросет|ассистент|виртуальн|елен[аыуе]\b|автоответ|по кругу",
    "нет живого человека в поддержке (шире бота)": r"\bбот\w*|\bробот(?!у)\w*|ассистент|виртуальн|помощник|живо[йгм]|елен[аыуе]\b|автоответ|по кругу|не соедин\w+|не переключ\w+|соедин\w+ с оператор|переключ\w+ на оператор|связ\w+ с (оператор|человек|поддержк|живым)|дозвон\w+|достучат\w+|поддержк",
    "в тексте названо приложение или кабинет": r"приложени|личн\w+ кабинет|виджет|\bлк\b",
    "самоподключение и списания": r"списыва|списал|снима|снял|подключа|подключил|подключен|навязыва|платн|подписк|развод|обман|воруют|воры|мошен|без моего|без спроса|без ведома|ева\b",
    "цены и тарифы": r"цен[аыуе]|тариф|подорож|дорого|дорож|повыш|повыс|рубл|абонентск",
    "связь и интернет": r"\bсвяз[ьи]\b(?! с )|интернет|не ловит|скорост|вышк|медленн|блокиров|покрыти|lte|4g|3g",
    "сбои приложения": r"не открыва|вылета|белый экран|глюч|тормоз|завис|не грузит|не загружа|ошибк|не работает|баг|лагает|крашит|слетает|не запуска",
    "вход и коды": r"вход|войти|авториз|парол|смс|код\b|коды|подтвержден|не прих",
    "интерфейс и понятность": r"шрифт|интерфейс|дизайн|неудобн|неудобно|непонятн|реклам|баннер|навязчив|запутан|сложно",
    "пополнение и оплата": r"пополн|оплат|платёж|платеж|карт[аыуой]|сбп|баланс",
}

with open(sys.argv[1], encoding="utf-8", newline="") as f:
    rows = [r for r in csv.DictReader(f) if int(r["rating"]) <= 2]

period = lambda d: "до 2026-07" if d < "2026-07-01" else ("2026-07..08" if d < "2026-09-01" else "с 2026-09")
tot = Counter(period(r["date"]) for r in rows)
hit = {t: Counter() for t in THEMES}
none = Counter()
for r in rows:
    txt = r["text"].lower()
    p = period(r["date"])
    found = [t for t, rx in THEMES.items() if re.search(rx, txt)]
    for t in found:
        hit[t][p] += 1
    if not [t for t in found if not t.startswith("в тексте названо")]:
        none[p] += 1

print("Отзывов с оценкой 1-2: %d (до 2026-07: %d, 2026-07..08: %d, с 2026-09: %d)" % (len(rows), tot["до 2026-07"], tot["2026-07..08"], tot["с 2026-09"]))
print("тема | всего | доля от 1-2, % | до 2026-07, % | 2026-07..08, % | с 2026-09, %")
for t in sorted(THEMES, key=lambda t: -sum(hit[t].values())):
    n = sum(hit[t].values())
    print("%s | %d | %.1f | %.1f | %.1f | %.1f" % (t, n, 100 * n / len(rows),
          100 * hit[t]["до 2026-07"] / tot["до 2026-07"], 100 * hit[t]["2026-07..08"] / tot["2026-07..08"], 100 * hit[t]["с 2026-09"] / tot["с 2026-09"]))
n0 = sum(none.values())
print("без темы по словарю | %d | %.1f" % (n0, 100 * n0 / len(rows)))
