def score(title, key, labs):
    print(title)
    for name, (prefix, lab) in labs.items():
        j = {int(x) for x in lab.split(",")}
        t = th(key, prefix)
        d = {i for i in range(1, 151) if key["flags"][str(i)][t]}
        tp, fp, fn = len(j & d), len(d - j), len(j - d)
        print("  %s: судья %d, словарь %d, совпало %d, лишних %d, пропущено %d | точность %.0f%%, полнота %.0f%%"
              % (name, len(j), len(d), tp, fp, fn, 100 * tp / len(d), 100 * tp / len(j)))


score("Старая часть (отзывы 1-2 до 2025-12-06):", OLD, OLD_LAB)
score("Прежняя выборка (последние 4000 отзывов):", RECENT, RECENT_LAB)
