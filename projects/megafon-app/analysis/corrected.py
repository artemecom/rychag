# Поправка долей словаря на точность и полноту, измеренные на выборке 150 отзывов (S014).
# доля_поправленная = доля_словаря * точность / полнота. Оценка: на выборке мало примеров, разброс порядка 7 п.п.
PRECISION = {"бот": 1.00, "нет живого человека": 0.68, "самоподключение": 0.48}
RECALL = {"бот": 0.96, "нет живого человека": 0.95, "самоподключение": 0.91}
BASE = {"бот": 22.5, "нет живого человека": 39.8, "самоподключение": 25.6}
for k in BASE:
    c = BASE[k] * PRECISION[k] / RECALL[k]
    print("%s: по словарю %.1f%%, с поправкой около %.1f%%" % (k, BASE[k], c))
c = BASE["самоподключение"] * PRECISION["самоподключение"] / RECALL["самоподключение"]
print("самоподключение, эффект с поправкой (доли возврата 15 / 30 / 45%%): %.1f / %.1f / %.1f п.п." % (c * 0.15, c * 0.30, c * 0.45))
