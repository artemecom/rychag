# Сравнение словаря тем с независимой разметкой судьи на выборке из 150 отзывов 1-2.
# Разметка судьи: агент «судья» без доступа к словарю и к рассуждениям автора, по одному критерию за вызов (2026-11-18).
import json
import sys

key = json.load(open(sys.argv[1], encoding="utf-8"))
F, T = key["flags"], key["themes"]
LAB = {
    "бот назван прямо": (T[0], "001, 002, 004, 007, 013, 016, 020, 022, 024, 025, 032, 034, 037, 047, 048, 049, 056, 057, 060, 062, 064, 065, 066, 067, 073, 078, 086, 087, 088, 091, 094, 096, 102, 103, 104, 106, 108, 112, 113, 119, 124, 127, 132, 134, 138, 150"),
    "нет живого человека": (T[1], "001, 004, 007, 016, 020, 022, 024, 025, 026, 032, 037, 047, 048, 049, 050, 057, 060, 062, 064, 065, 066, 067, 078, 086, 091, 094, 096, 102, 106, 108, 112, 113, 118, 119, 121, 124, 127, 132, 135, 141, 150"),
    "самоподключение и списания": (T[3], "012, 014, 022, 028, 036, 039, 040, 046, 051, 056, 076, 089, 097, 104, 107, 109, 114, 116, 134, 135, 142, 150"),
}
for name, (theme, lab) in LAB.items():
    j = {int(x) for x in lab.split(",")}
    d = {i for i in range(1, 151) if F[str(i)][theme]}
    tp, fp, fn = len(j & d), len(d - j), len(j - d)
    print("%s: судья %d, словарь %d, совпало %d, лишних %d, пропущено %d | точность %.0f%%, полнота %.0f%%, доля судья %.1f%% / словарь %.1f%%"
          % (name, len(j), len(d), tp, fp, fn, 100 * tp / len(d), 100 * tp / len(j), 100 * len(j) / 150, 100 * len(d) / 150))
