"""Цепочка эффекта: сколько номеров сохранят доступ к интернету (допущения низ/основа/верх).
Слабый ход: берутся нижние значения пользы. Сильный: верхние. Основной: основные."""
S = {
    "слабый":   dict(G=6500, p=40, e=1, r=8,  q=10, qc=0),
    "основной": dict(G=7250, p=60, e=3, r=12, q=25, qc=5),
    "сильный":  dict(G=8000, p=80, e=6, r=16, q=40, qc=15),
}
for name, v in S.items():
    G, p, e, r, q, qc = v["G"], v["p"], v["e"], v["r"], v["q"], v["qc"]
    cases = G * p / 100 * e / 2          # полгода работы
    restricted = cases * r / 100
    prev_simple = restricted * q / 100
    prev_cab = restricted * (q + qc) / 100
    print(f"{name}: подходящих случаев за полгода {cases:.0f}; ограничений без помощи {restricted:.0f}; "
          f"предотвращено простым предупреждением {prev_simple:.0f}; предотвращено кабинетом {prev_cab:.0f}")
